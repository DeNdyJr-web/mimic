#!/usr/bin/env node
// Generates the exact `TranslationKey` literal union used to type the i18n `t()` helper.
//
// WHY THIS EXISTS (Milestone 4):
//   The original `KeysOf<T>` recursive mapped type in src/locales/index.ts flattens nested keys into individual
//   names ("home" | "title") instead of dotted paths ("home.title"). Since t()'s runtime lookup splits on ".",
//   EVERY valid nested key failed typechecking, blocking all components. Recursive template-literal recursion also
//   collapses to `never` in this sandbox's TypeScript, so a generated literal union is the only robust fix.
//
// HOW IT WORKS:
//   Recursively walks en.json (the single source of truth for keys) and emits every dotted key path — both
//   INTERMEDIATE and LEAF nodes — to src/locales/translationKeys.ts, preserving the original KeysOf contract.
//
// RUN AFTER EDITING en.json:
//   npm run gen:keys
//
// NOTE: This only touches TYPES, never locale content. validate:locales stays green as long as all 7 locale files
// stay in sync with en.json (see scripts/validate-locales.mjs).

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const EN_PATH = join(ROOT, 'src', 'locales', 'en.json');
const OUT_PATH = join(ROOT, 'src', 'locales', 'translationKeys.ts');

/** Collect every dotted key path (intermediate + leaf) from a nested object via pre-order DFS. */
function collectPaths(node, prefix, out) {
  for (const key of Object.keys(node)) {
    const full = prefix ? `${prefix}.${key}` : key;
    const value = node[key];
    out.push(full);
    if (value !== null && typeof value === 'object' && !Array.isArray(value)) {
      collectPaths(value, full, out);
    }
  }
}

const en = JSON.parse(readFileSync(EN_PATH, 'utf8'));
const paths = [];
collectPaths(en, '', paths);

// Deterministic ordering: top-level keys in file order, then children — matches the original KeysOf traversal.
const lines = [
  '// AUTO-GENERATED by scripts/gen-translation-keys.mjs — do not edit by hand.',
  '// Run `npm run gen:keys` after changing en.json. See that script for why this exists (Milestone 4).',
  '',
  'export type TranslationKey =',
  ...paths.map((p) => `  | ${JSON.stringify(p)}`,),
  ';',
  '',
];

mkdirSync(dirname(OUT_PATH), { recursive: true });
writeFileSync(OUT_PATH, lines.join('\n'), 'utf8');

const rel = relative(process.cwd(), OUT_PATH);
console.log(`[gen:keys] wrote ${paths.length} key paths -> ${rel}`);
